# Membuat list pizza
pizzas = ["Pepperoni", "Cheese", "Mushroom", "Chicken", "Beef", "Tuna"]

# Menampilkan 3 pizza pertama
print("The first three items in the list are:")
print(pizzas[:3])

# Menampilkan 3 pizza tengah
print("Three items from the middle of the list are:")
print(pizzas[2:5])

# Menampilkan 3 pizza terakhir
print("The last three items in the list are:")
print(pizzas[-3:])
